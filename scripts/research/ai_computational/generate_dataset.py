#!/usr/bin/env python3
"""Generate synthetic inputs only. No Laravel calls or personal data."""
import argparse
import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DEFAULT = ROOT / "research/ai_computational"
COLS = ["case_id","dataset","seed","mastery_score","evidence_count","prereq1_state","prereq1_mastery","prereq1_evidence","prereq2_state","prereq2_mastery","prereq2_evidence","next_context","scenario"]
EXPECTED = {"dataset_grid.csv": 336, "dataset_boundary.csv": 128,
            "dataset_scenario.csv": 16, "dataset_random.csv": 1000,
            "dataset_reference.csv": 8}

def fmt(n):
    return f"{n // 100}.{n % 100:02d}"

def row(cid, group, seed, m, e, ps, nxt, note):
    out = [cid, group, seed, fmt(m), e]
    for i in range(2):
        if i >= len(ps):
            out.extend(["absent", "", ""])
        elif ps[i] is None:
            out.extend(["missing", "", ""])
        else:
            p, pe = ps[i]
            out.extend(["observed", fmt(p), pe])
    return out + [nxt, note]

def generate(c):
    out = {}
    for key, group in [("grid", "D1"), ("boundary", "D2")]:
        a = []
        for m in c[key]["mastery_cents"]:
            for e in c[key]["evidence"]:
                for p in c[key]["prerequisite_cents"]:
                    a.append(row(f"{group}-{len(a)+1:03d}", group, "", m, e,
                                 [(p, c["fixed_prerequisite_evidence"])], "ready", key))
        out[f"dataset_{key}.csv"] = [COLS] + a
    out["dataset_scenario.csv"] = [COLS] + [
        row(f"S{i:02d}", "D3", "", m, e,
            [None if p is None else (p, c["fixed_prerequisite_evidence"]) for p in ps], nxt, note)
        for i, (m, e, ps, nxt, note) in enumerate(c["scenarios"], 1)]
    a = []
    for seed in c["seeds"]:
        state = seed
        def draw(n):
            nonlocal state
            limit = 2**32 - (2**32 % n)
            while True:
                state = (1664525 * state + 1013904223) % 2**32
                if state < limit:
                    return state % n
        def observed():
            return (draw(10001), draw(21))
        for i in range(c["per_seed"]):
            pattern = c["prereq_patterns"][i % 5]
            nxt = c["next_patterns"][(i // 5) % 5]
            m, e = draw(10001), draw(21)
            if pattern == "none":
                ps = []
            elif pattern == "single_observed":
                ps = [observed()]
            elif pattern == "single_missing":
                ps = [None]
            elif pattern == "double_observed":
                ps = [observed(), observed()]
            elif pattern == "double_mixed":
                ps = [observed(), None]
            else:
                raise ValueError(pattern)
            a.append(row(f"D4-{seed}-{i+1:03d}", "D4", seed, m, e, ps, nxt, pattern))
    out["dataset_random.csv"] = [COLS] + a
    out["dataset_reference.csv"] = [[
        "case_id", "mastery_score", "evidence_count", "prerequisite_mastery",
        "reference_centroid", "reference_selected_output"]] + [
        [f"N{i:02d}", fmt(m), e, fmt(p), cent, label]
        for i, (m, e, p, cent, label) in enumerate(c["reference"], 1)]
    return out

def serialize(rows):
    buf = io.StringIO(newline="")
    csv.writer(buf, lineterminator="\n").writerows(rows)
    return buf.getvalue().encode("ascii")

def checksum(data):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) % 2**32
    return f"{h:08x}"

def validate(datasets):
    ids = set()
    for name, rows in datasets.items():
        if len(rows)-1 != EXPECTED[name]:
            raise ValueError(f"Unexpected count: {name}")
        for r in rows[1:]:
            if r[0] in ids or len(r) != len(rows[0]):
                raise ValueError(f"Duplicate ID or width: {r[0]}")
            ids.add(r[0])
            if name == "dataset_reference.csv":
                continue
            if not 0 <= float(r[3]) <= 100 or not isinstance(r[4], int) or r[4] < 0:
                raise ValueError(f"Invalid current input: {r[0]}")
            for j in (5, 8):
                if r[j] == "observed":
                    if not 0 <= float(r[j+1]) <= 100 or not isinstance(r[j+2], int) or r[j+2] < 0:
                        raise ValueError(f"Invalid prerequisite: {r[0]}")
                elif r[j] not in ("absent", "missing") or r[j+1:j+3] != ["", ""]:
                    raise ValueError(f"Invalid missingness: {r[0]}")
    if set(datasets) != set(EXPECTED):
        raise ValueError("Unexpected dataset names")

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--config", type=Path, default=DEFAULT / "config/experiment.json")
    p.add_argument("--output", type=Path, default=DEFAULT / "datasets")
    p.add_argument("--check", action="store_true", help="Compare generated bytes with checked-in CSVs")
    args = p.parse_args()
    c = json.loads(args.config.read_text(encoding="utf-8"))
    datasets = generate(c)
    validate(datasets)
    if not args.check:
        args.output.mkdir(parents=True, exist_ok=True)
    for name, rows in datasets.items():
        data = serialize(rows)
        path = args.output / name
        if args.check:
            if path.read_bytes() != data:
                raise SystemExit(f"Byte mismatch: {name}")
        else:
            path.write_bytes(data)
        print(f"{name}: {len(rows)-1} rows; fnv1a32={checksum(data)}")
    print("Synthetic inputs only; no algorithm executions or participant data.")

if __name__ == "__main__":
    main()
